#!/usr/bin/env node
/**
 * ⚠ SUPERSEDED (2026-07-03): this script targets the old `published` boolean,
 * which was replaced by the `status` column in migrate-v2-status.sql, and the
 * stale-series rows it fixes no longer exist in the DB. Do not run.
 * Use the new integrity check script instead (see scripts/check-integrity.js).
 *
 * scripts/migrate-integrity.js
 *
 * Fixes the two data-integrity issues found in the storage audit:
 *
 *   A) Rows with stale series values (drop / process / meaning) that were
 *      inserted before commit f11198f synced VALID_SERIES with FilterBar.
 *      Fix: set published = false so they are hidden but NOT deleted.
 *      Action required: manually assign the correct series slug and re-publish.
 *
 *   B) Rows where storage_path is missing the canonical 'images/' prefix
 *      (possible from manual inserts or a prior upload tool).
 *      Fix: update storage_path to 'images/<original>' only when the file
 *      is confirmed to exist at the corrected path in Supabase Storage.
 *
 * Files that do not exist in storage are NEVER modified — they are logged
 * and written as comments in the generated SQL for manual investigation.
 *
 * ──────────────────────────────────────────────────────────────────────────────
 * USAGE
 *
 *   Dry-run (default):
 *     node scripts/migrate-integrity.js
 *   → Prints findings to stdout and writes scripts/migration-output.sql.
 *     Nothing in the database is touched. Review the SQL before continuing.
 *
 *   Apply (recommended path — use the generated SQL):
 *     1. Open Supabase dashboard → SQL Editor → New query
 *     2. Paste contents of scripts/migration-output.sql  (BEGIN / COMMIT wrapped)
 *     3. Run — if anything fails the whole block is rolled back automatically.
 *
 *   Apply via this script (JS convenience mode, no true DB transaction):
 *     node scripts/migrate-integrity.js --apply
 *   → Executes changes one by one. On any failure it attempts to reverse all
 *     previously applied changes (compensating rollback). Because this is not
 *     a real DB transaction, prefer the SQL approach for production.
 *
 * ──────────────────────────────────────────────────────────────────────────────
 * REQUIREMENTS
 *
 *   .env.local must contain:
 *     NEXT_PUBLIC_SUPABASE_URL
 *     SUPABASE_SERVICE_ROLE_KEY   ← required for --apply (anon key can't bypass RLS)
 *     NEXT_PUBLIC_SUPABASE_ANON_KEY  ← used for read-only dry-run if no service key
 */

'use strict'

const fs   = require('fs')
const path = require('path')
const { createClient } = require('@supabase/supabase-js')

const BUCKET       = 'aitiopia-images'
const PATH_PREFIX  = 'images'
const VALID_SERIES = new Set(['letters', 'words', 'miscellaneous', 'year'])
const APPLY        = process.argv.includes('--apply')
const SQL_OUT      = path.join(__dirname, 'migration-output.sql')

// ── .env.local loader ─────────────────────────────────────────────────────────
function loadEnv() {
  const envPath = path.join(__dirname, '..', '.env.local')
  if (!fs.existsSync(envPath)) die(`.env.local not found at ${envPath}`)
  const env = {}
  for (const raw of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq === -1) continue
    env[line.slice(0, eq).trim()] = line.slice(eq + 1).trim()
  }
  return env
}

function die(msg) { console.error(`\n✗ ${msg}\n`); process.exit(1) }
function pad(n, w = 2) { return String(n).padStart(w, '0') }
function sqlLit(val) { return `'${String(val).replace(/'/g, "''")}'` }

// ── storage existence check (HEAD request to the public URL) ──────────────────
async function fileExists(supabaseUrl, storagePath) {
  const url = `${supabaseUrl}/storage/v1/object/public/${BUCKET}/${storagePath}`
  try {
    const res = await fetch(url, { method: 'HEAD' })
    return res.ok   // 200 → exists, 400/404 → missing
  } catch {
    return false    // network error — treat as missing
  }
}

// ── SQL file builder ──────────────────────────────────────────────────────────
function buildSql({ pathFixes, flagged, missing }) {
  const ts = new Date().toISOString()
  const L  = []

  L.push(`-- AItiopia data-integrity migration`)
  L.push(`-- Generated by scripts/migrate-integrity.js at ${ts}`)
  L.push(`-- Run in Supabase dashboard → SQL Editor → New query`)
  L.push(`--`)
  L.push(`-- This file is wrapped in a transaction. If any statement fails,`)
  L.push(`-- the entire migration is rolled back automatically.`)
  L.push(``)
  L.push(`BEGIN;`)
  L.push(``)

  // ── A: storage_path prefix corrections ─────────────────────────────────────
  if (pathFixes.length > 0) {
    L.push(`-- ── A: storage_path prefix fix (${pathFixes.length} row(s)) ──────────────────────────`)
    for (const { id, oldPath, newPath } of pathFixes) {
      L.push(`-- [${id}] ${oldPath} → ${newPath}`)
      L.push(`UPDATE images`)
      L.push(`  SET    storage_path = ${sqlLit(newPath)}`)
      L.push(`  WHERE  id           = ${sqlLit(id)}`)
      L.push(`  AND    storage_path = ${sqlLit(oldPath)};  -- guard: no-op if already fixed`)
      L.push(``)
    }
  } else {
    L.push(`-- A: no storage_path prefix issues found.`)
    L.push(``)
  }

  // ── B: stale series → unpublished ──────────────────────────────────────────
  if (flagged.length > 0) {
    L.push(`-- ── B: stale series values → published = false (${flagged.length} row(s)) ──────────`)
    L.push(`--`)
    L.push(`-- These rows have series values that existed before the FilterBar sync`)
    L.push(`-- (commit f11198f). Their files ARE in storage — they are hidden, not deleted.`)
    L.push(`-- After running this migration, open Supabase dashboard, find each row by id,`)
    L.push(`-- assign the correct series slug, then set published = true.`)
    L.push(`--`)
    for (const { id, storagePath, series } of flagged) {
      L.push(`-- [${id}]  series='${series}'  path=${storagePath}`)
    }
    L.push(``)

    // Single UPDATE for all flagged IDs so it's one atomic statement
    const idList = flagged.map(r => sqlLit(r.id)).join(`,\n             `)
    L.push(`UPDATE images`)
    L.push(`  SET    published = false`)
    L.push(`  WHERE  id IN (`)
    L.push(`             ${idList}`)
    L.push(`           )`)
    L.push(`  AND    published = true;  -- no-op for rows already unpublished`)
    L.push(``)
  } else {
    L.push(`-- B: no stale series values found.`)
    L.push(``)
  }

  // ── C: genuinely missing files — no action ─────────────────────────────────
  if (missing.length > 0) {
    L.push(`-- ── C: files NOT found in storage (${missing.length} row(s)) — NO ACTION TAKEN ─────`)
    L.push(`--`)
    L.push(`-- These rows are left untouched per the migration rules.`)
    L.push(`-- Investigate: the storage object may have been manually deleted,`)
    L.push(`-- the path may be completely wrong, or the file was never uploaded.`)
    L.push(`-- To remove a row only after manually confirming the file is gone:`)
    L.push(`--   DELETE FROM images WHERE id = '<id>';`)
    L.push(`--`)
    for (const { id, storagePath, series } of missing) {
      L.push(`-- [${id}]  series='${series}'  path=${storagePath}`)
    }
    L.push(``)
  } else {
    L.push(`-- C: no genuinely missing storage files found.`)
    L.push(``)
  }

  if (pathFixes.length === 0 && flagged.length === 0 && missing.length === 0) {
    L.push(`-- Database is clean — nothing to change.`)
    L.push(``)
  }

  L.push(`COMMIT;`)
  return L.join('\n')
}

// ── compensating rollback for --apply mode ────────────────────────────────────
async function reverseChanges(supabase, applied) {
  if (applied.length === 0) return
  console.error('\nAttempting compensating rollback of applied changes…')
  for (const op of [...applied].reverse()) {
    try {
      if (op.type === 'path') {
        await supabase.from('images')
          .update({ storage_path: op.oldPath })
          .eq('id', op.id)
          .eq('storage_path', op.newPath)
        console.error(`  ↩ [${op.id}] storage_path restored to ${op.oldPath}`)
      } else if (op.type === 'flag') {
        await supabase.from('images')
          .update({ published: true })
          .in('id', op.ids)
        console.error(`  ↩ [${op.ids.join(', ')}] published restored to true`)
      }
    } catch {
      console.error(`  ✗ rollback failed for [${op.id ?? op.ids}] — fix manually`)
    }
  }
}

// ── main ──────────────────────────────────────────────────────────────────────
async function main() {
  const env = loadEnv()
  const supabaseUrl = env.NEXT_PUBLIC_SUPABASE_URL
  const supabaseKey = env.SUPABASE_SERVICE_ROLE_KEY ?? env.NEXT_PUBLIC_SUPABASE_ANON_KEY
  if (!supabaseUrl) die('NEXT_PUBLIC_SUPABASE_URL missing from .env.local')
  if (!supabaseKey) die('No Supabase key found in .env.local')
  if (APPLY && !env.SUPABASE_SERVICE_ROLE_KEY) {
    die('--apply requires SUPABASE_SERVICE_ROLE_KEY — anon key cannot bypass RLS for writes')
  }

  const supabase = createClient(supabaseUrl, supabaseKey)

  console.log('\n┌──────────────────────────────────────────────┐')
  console.log(`│  AItiopia integrity migration                 │`)
  console.log(`│  mode : ${APPLY ? 'APPLY (JS — use SQL for production)' : 'dry-run                        '}  │`)
  console.log('└──────────────────────────────────────────────┘\n')

  // ── 1. Fetch all rows ──────────────────────────────────────────────────────
  const { data: images, error: fetchErr } = await supabase
    .from('images')
    .select('id, storage_path, series, published')
    .order('id')
  if (fetchErr) die(`DB query failed: ${fetchErr.message}`)
  console.log(`Loaded ${images.length} row(s) from images table.`)
  console.log(`Checking each against Supabase Storage via HEAD request…\n`)

  // ── 2. Categorise every row ────────────────────────────────────────────────
  const pathFixes = []   // { id, oldPath, newPath }
  const flagged   = []   // { id, storagePath, series } — stale series, file OK
  const missing   = []   // { id, storagePath, series } — file not in storage
  const clean     = []   // ids that need no change

  for (let i = 0; i < images.length; i++) {
    const { id, storage_path, series } = images[i]
    const prefix = `  [${pad(i + 1)}/${pad(images.length)}] ${id.slice(0, 8)}…`
    process.stdout.write(prefix)

    const validSeries = VALID_SERIES.has(series)
    const hasPrefix   = storage_path.startsWith(`${PATH_PREFIX}/`)

    const existsAtCurrent = await fileExists(supabaseUrl, storage_path)

    if (!existsAtCurrent && !hasPrefix) {
      // Try canonical prefix — maybe the path was stored without 'images/'
      const corrected = `${PATH_PREFIX}/${storage_path}`
      const existsAtCorrected = await fileExists(supabaseUrl, corrected)
      if (existsAtCorrected) {
        process.stdout.write(`  PATH FIX   ${storage_path}  →  ${corrected}\n`)
        pathFixes.push({ id, oldPath: storage_path, newPath: corrected })
        continue
      }
    }

    if (!existsAtCurrent) {
      const reason = validSeries ? 'file missing' : 'file missing + stale series'
      process.stdout.write(`  MISSING    [${reason}]  path=${storage_path}\n`)
      missing.push({ id, storagePath: storage_path, series })
      continue
    }

    if (!validSeries) {
      process.stdout.write(`  FLAG       series='${series}' not in valid set\n`)
      flagged.push({ id, storagePath: storage_path, series })
      continue
    }

    process.stdout.write(`  ok\n`)
    clean.push(id)
  }

  // ── 3. Print summary ───────────────────────────────────────────────────────
  console.log('\n' + '═'.repeat(56))
  console.log('  Results')
  console.log('─'.repeat(56))
  console.log(`  ✓ clean (no action)              : ${clean.length}`)
  console.log(`  ~ path-prefix fix needed         : ${pathFixes.length}`)
  console.log(`  ~ stale series → will unpublish  : ${flagged.length}`)
  console.log(`  ✗ missing in storage (logged)    : ${missing.length}`)
  console.log('═'.repeat(56))

  if (pathFixes.length > 0) {
    console.log('\nPath fixes:')
    for (const { id, oldPath, newPath } of pathFixes)
      console.log(`  [${id}]\n    ${oldPath}\n    → ${newPath}`)
  }

  if (flagged.length > 0) {
    console.log('\nStale-series rows (file exists, will be set published=false):')
    for (const { id, storagePath, series } of flagged)
      console.log(`  [${id}]  series='${series}'  path=${storagePath}`)
  }

  if (missing.length > 0) {
    console.log('\nMissing-file rows (no action — investigate manually):')
    for (const { id, storagePath, series } of missing)
      console.log(`  [${id}]  series='${series}'  path=${storagePath}`)
  }

  // ── 4. Write SQL ───────────────────────────────────────────────────────────
  const sql = buildSql({ pathFixes, flagged, missing })
  fs.writeFileSync(SQL_OUT, sql, 'utf8')
  const relOut = path.relative(process.cwd(), SQL_OUT)
  console.log(`\nSQL written → ${relOut}`)

  if (!APPLY) {
    console.log('\nDry run complete.')
    console.log('Recommended next step: paste migration-output.sql into')
    console.log('Supabase dashboard → SQL Editor and run it there (true transaction).')
    console.log('\nOr re-run with --apply to apply via this script.\n')
    return
  }

  // ── 5. Apply mode (JS compensating rollback) ───────────────────────────────
  if (pathFixes.length === 0 && flagged.length === 0) {
    console.log('\nNothing to apply.\n')
    return
  }

  console.log('\nApplying changes…')
  const applied = []

  try {
    // A: path fixes — one UPDATE per row so the guard condition is per-row
    for (const { id, oldPath, newPath } of pathFixes) {
      const { error } = await supabase
        .from('images')
        .update({ storage_path: newPath })
        .eq('id', id)
        .eq('storage_path', oldPath)
      if (error) throw new Error(`Path fix failed for [${id}]: ${error.message}`)
      applied.push({ type: 'path', id, oldPath, newPath })
      console.log(`  ✓ [${id}] storage_path: ${oldPath} → ${newPath}`)
    }

    // B: stale series — single batch UPDATE
    if (flagged.length > 0) {
      const ids = flagged.map(r => r.id)
      const { error } = await supabase
        .from('images')
        .update({ published: false })
        .in('id', ids)
        .eq('published', true)
      if (error) throw new Error(`Series flag failed: ${error.message}`)
      applied.push({ type: 'flag', ids })
      for (const { id, series } of flagged)
        console.log(`  ~ [${id}] published → false  (was series='${series}')`)
    }
  } catch (err) {
    console.error(`\n✗ Apply error: ${err.message}`)
    await reverseChanges(supabase, applied)
    process.exit(1)
  }

  console.log(`\n✓ ${applied.length} operation(s) applied successfully.`)
  console.log(`  The generated SQL at ${relOut} reflects what was done.\n`)
}

main().catch(err => { console.error('\nFatal:', err.message); process.exit(1) })
